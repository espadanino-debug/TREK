// Renders the watermark text to a PNG and writes it into lib/image/watermark-data.ts.
// The PNG is baked into the code so the server never needs system fonts (Vercel has none).
//
// Usage: npm run make-watermark -- "Made with Colorly"
import sharp from "sharp";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const text = process.argv[2] || "Made with Colorly";
const escaped = text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const fontSize = 40;
const height = 72;
const width = Math.round(text.length * fontSize * 0.62 + 72);

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
  <rect x="0" y="0" width="${width}" height="${height}" rx="${height / 2}" fill="#ffffff" fill-opacity="0.9" stroke="#9ca3af" stroke-width="2"/>
  <text x="${width / 2}" y="${height / 2 + fontSize * 0.35}" font-family="DejaVu Sans, Arial, Helvetica, sans-serif"
        font-size="${fontSize}" font-weight="bold" fill="#6b7280" text-anchor="middle">${escaped}</text>
</svg>`;

const png = await sharp(Buffer.from(svg), { density: 144 }).png().toBuffer();
const out = fileURLToPath(new URL("../lib/image/watermark-data.ts", import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/make-watermark.mjs. Do not edit by hand.\n// Text: ${JSON.stringify(text)}\nexport const WATERMARK_PNG_BASE64 =\n  "${png.toString("base64")}";\n`,
);
console.log(`Wrote ${out} (${png.length} bytes) for text: ${text}`);
